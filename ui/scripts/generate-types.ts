/**
 * Generate each widget's `<Widget>.type.d.ts` from its `<Widget>.schema.json`.
 *
 * The schema is the source of truth: it is what the portal validates a widget CR against, and the
 * CRD is generated from it. The type file is derived and committed, so it must never be edited by
 * hand. Seven of them were, and a regeneration rewrote 285 lines of them.
 *
 * `--check` regenerates in memory and fails, naming each file, when a committed type file differs
 * from what its schema produces, when a schema fails to compile, or when a type file has no schema
 * left to generate it. CI runs it, so a hand edit or a schema change without a regeneration fails
 * the pull request.
 */
import { promises as fs } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { compileFromFile } from 'json-schema-to-typescript'

// For __dirname in ES modules
const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)

const uiDir = path.resolve(__dirname, '..')
const baseDir = path.resolve(uiDir, 'src/widgets')

// Shared schema fragments compiled to a single canonical type. They live OUTSIDE
// src/widgets so the CRD generator does not turn them into per-widget CRDs. The
// actions fragment is the single source of truth for the WidgetActions shape —
// every action-bearing widget copies it verbatim into widgetData.actions.
const sharedSchemas = [
  {
    input: path.resolve(uiDir, 'src/schemas/actions.schema.json'),
    output: path.resolve(uiDir, 'src/types/actions.generated.d.ts'),
  },
]

const compileOptions = {
  bannerComment: '',
  style: {
    semi: false,
    singleQuote: true,
  },
}

async function walkDir(dir: string): Promise<string[]> {
  const entries = await fs.readdir(dir, { withFileTypes: true })
  const nested = await Promise.all(entries.map(async (entry) => {
    const entryPath = path.join(dir, entry.name)
    return entry.isDirectory() ? walkDir(entryPath) : [entryPath]
  }))
  return nested.flat()
}

const relative = (file: string) => path.relative(uiDir, file)

async function generateTypes() {
  const check = process.argv.includes('--check')
  const files = await walkDir(baseDir)

  const targets = [
    ...files
      .filter((file) => file.endsWith('.schema.json'))
      .map((input) => ({ input, output: input.replace(/\.schema\.json$/, '.type.d.ts') })),
    ...sharedSchemas,
  ].sort((left, right) => left.output.localeCompare(right.output))

  const failed: string[] = []
  const drifted: string[] = []

  await Promise.all(targets.map(async ({ input, output }) => {
    let next: string
    try {
      next = await compileFromFile(input, compileOptions)
    } catch (err) {
      console.error(`Failed to compile ${relative(input)}:`, err)
      failed.push(relative(input))
      return
    }

    if (!check) {
      await fs.writeFile(output, next)
      console.log(`Generated: ${relative(output)}`)
      return
    }

    const current = await fs.readFile(output, 'utf8').catch(() => null)
    if (current !== next) {
      drifted.push(relative(output))
    }
  }))

  // A type file whose schema is gone is generated by nothing, so it would never drift and never
  // be checked again.
  const generated = new Set(targets.map(({ output }) => output))
  const orphaned = files
    .filter((file) => file.endsWith('.type.d.ts') && !generated.has(file))
    .map(relative)
    .sort()

  for (const file of failed.sort()) {
    console.error(`::error file=ui/${file}::the schema does not compile, so its type file cannot be checked`)
  }
  for (const file of drifted.sort()) {
    console.error(`::error file=ui/${file}::differs from what its schema generates`)
  }
  for (const file of orphaned) {
    console.error(`::error file=ui/${file}::no schema generates this type file`)
  }

  if (failed.length > 0 || (check && (drifted.length > 0 || orphaned.length > 0))) {
    if (check && drifted.length > 0) {
      console.error(`${drifted.length} type file(s) are out of date with their schemas: ${drifted.sort().join(', ')}`)
      console.error('Run `npm run generate-types` and commit the result. Do not edit a .type.d.ts by hand: change its schema.')
    }
    process.exit(1)
  }

  console.log(check
    ? `all ${targets.length} generated type files match their schemas`
    : `generated ${targets.length} type files`)
}

